import json
from collections.abc import Iterable, Mapping, Sequence
from typing import Any

from tienlen.lab.step import PENDING, PROMOTED, REFERENCE, REJECTED

Row = Mapping[str, Any]
HEADER = """# Model evolution

Models grown one change at a time, from the simplest possible. This page is generated by `tienlen lab report` from the `experiments` table, so edit the table, not this file.

**Method.** Every step trains 3 seeds on the same game budget, then plays one fixed suite: the same seeded deals with rotated seats, 2-player default rules, top-scoring move, against random, greedy, and the current best step. Win rates are means over seeds, with the standard deviation. The promotion rule was fixed before any results: the best seed, chosen by its win rates against random and greedy, must beat the parent's best head-to-head with a 95% Wilson interval excluding 50%. Rejected steps stay here, and the parent stays the base for the next step.
"""


def _results(row: Row) -> dict[str, Any]:
    return json.loads(row["results"]) if row["results"] else {}


def _rate(summary: Mapping[str, Mapping[str, float]], role: str) -> str:
    entry = summary.get(role)
    return f"{entry['mean']:.1%} ± {entry['stdev']:.1%}" if entry else "-"


def _h2h(results: Mapping[str, Any]) -> str:
    match results.get("head_to_head"):
        case None:
            return "-"
        case pairing:
            low, high = pairing["ci_low"], pairing["ci_high"]
            return f"{pairing['win_rate']:.1%} ({low:.1%}–{high:.1%}) vs `{pairing['opponent']}`"


def _cell(text: str | None) -> str:
    return (text or "-").replace("|", "\\|").replace("\n", " ")


def _rating(row: Row, ratings: Mapping[str, float]) -> str:
    value = ratings.get(row["bot_ref"])
    return f"{value:.1f}" if value is not None else "-"


def step_rows(rows: Iterable[Row], ratings: Mapping[str, float]) -> list[str]:
    lines = [
        (
            "| Step | Model | Change | Hypothesis | vs random | vs greedy | Head-to-head | "
            "Rating | Verdict |"
        ),
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        results = _results(row)
        summary = results.get("summary", {})
        cells = [
            str(row["step"]),
            f"`{row['bot_ref']}`",
            _cell(row["change"]),
            _cell(row["hypothesis"]),
            _rate(summary, "random"),
            _rate(summary, "greedy"),
            _h2h(results),
            _rating(row, ratings),
            f"**{row['verdict']}**",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def _greedy_mean(row: Row) -> float:
    return _results(row).get("summary", {}).get("greedy", {}).get("mean", 0.0)


def _story_line(row: Row, previous: float | None) -> str:
    mean = _greedy_mean(row)
    gain = f" ({mean - previous:+.1%} vs greedy)" if previous is not None else ""
    note = f" {row['notes']}" if row["notes"] else ""
    return f"- **Step {row['step']}: {row['change']}**{gain}.{note}"


def _helped(rows: Sequence[Row]) -> list[str]:
    lines = ["## What helped", ""]
    previous = None
    gains = []
    for row in rows:
        if row["verdict"] == PROMOTED:
            gains.append((_greedy_mean(row) - (previous or 0.0), row, previous))
            previous = _greedy_mean(row)
    ordered = sorted(gains, key=lambda item: (item[2] is not None, item[0]), reverse=True)
    lines += [_story_line(row, before) for _, row, before in ordered] or ["Nothing yet."]
    return lines


def _did_not_help(rows: Sequence[Row]) -> list[str]:
    rejected = [row for row in rows if row["verdict"] == REJECTED]
    lines = ["## What didn't help", ""]
    return lines + ([_story_line(row, None) for row in rejected] or ["Nothing rejected."])


def _reference(rows: Sequence[Row]) -> list[str]:
    found = [row for row in rows if row["verdict"] == REFERENCE]
    if not found:
        return []
    row = found[0]
    pairings = _results(row)["pairings"]
    lines = ["## Outside reference", "", "| Opponent | Win rate | 95% CI |", "|---|---|---|"]
    lines += [
        f"| `{p['opponent']}` | {p['win_rate']:.1%} | {p['ci_low']:.1%}–{p['ci_high']:.1%} |"
        for p in pairings.values()
    ]
    note = [row["notes"]] if row["notes"] else []
    return [*lines[:2], f"`{row['bot_ref']}` on the same suite.", "", *lines[2:], "", *note]


def render(rows: Sequence[Row], ratings: Mapping[str, float]) -> str:
    steps = [row for row in rows if row["verdict"] not in (REFERENCE, PENDING)]
    sections = [
        HEADER.rstrip(),
        "\n".join(["## Steps", "", *step_rows(steps, ratings)]),
        "\n".join(_helped(steps)),
        "\n".join(_did_not_help(steps)),
        "\n".join(_reference(rows)),
    ]
    return "\n\n".join(section for section in sections if section) + "\n"
